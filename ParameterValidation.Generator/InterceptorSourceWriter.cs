using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;

namespace ParameterValidation.Generator;

/// <summary>Writes the interceptors for every call site: one per method, validating, then forwarding.</summary>
internal static class InterceptorSourceWriter
{
    public const string HintName = "ParameterValidationInterceptors.g.cs";

    private const string ValidationAttributeArray =
        "global::System.ComponentModel.DataAnnotations.ValidationAttribute[]";
    private const string MemberIndent = "        ";
    private const string BodyIndent = "            ";
    private const string Separator = ", ";
    private const string NewLine = "\n";

    private const string Header = """
        // <auto-generated/>
        #nullable enable

        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = true)]
            file sealed class InterceptsLocationAttribute : global::System.Attribute
            {
                public InterceptsLocationAttribute(int version, string data) { }
            }
        }

        namespace ParameterValidation.Generated
        {
            file static class ParameterValidationInterceptors
            {

        """;

    private const string Footer = """
                private static void Validate(
                    object? value,
                    string parameterName,
                    global::System.ComponentModel.DataAnnotations.ValidationAttribute[] attributes)
                {
                    foreach (var attribute in attributes)
                    {
                        if (attribute.IsValid(value))
                        {
                            continue;
                        }

                        if (value is null
                        && attribute is global::System.ComponentModel.DataAnnotations.RequiredAttribute)
                        {
                            throw new global::System.ArgumentNullException(
                                parameterName,
                                attribute.FormatErrorMessage(parameterName));
                        }

                        throw new global::System.ArgumentException(
                        attribute.FormatErrorMessage(parameterName),
                        parameterName);
                    }
                }
            }
        }

        """;

    /// <remarks>Every call to the same method shares one interceptor.</remarks>
    public static string Write(ImmutableArray<CallSite> callSites)
    {
        IEnumerable<string> interceptors = callSites
            .GroupBy(static site => site.MethodId)
            .Select(static (group, index) => WriteInterceptor([.. group], $"Intercept{index}"));
        return Header + string.Concat(interceptors) + Footer;
    }

    private static string WriteInterceptor(ImmutableArray<CallSite> sites, string name)
    {
        CallSite first = sites[0];
        string returnPrefix = first.ReturnsVoid
            ? string.Empty
            : "return ";
        IEnumerable<string> lines =
        [
            .. first.Checks.Select(check => MemberIndent + WriteAttributeField(check, name)),
            .. sites.Select(static site => MemberIndent + site.InterceptsLocationAttribute),
            MemberIndent + "public static " + string.Format(first.Signature, name),
            MemberIndent + "{",
            .. first.Checks.Select(check => BodyIndent + WriteValidation(check, name)),
            $"{BodyIndent}{returnPrefix}{first.ForwardingCall};",
            MemberIndent + "}",
            string.Empty,
        ];
        return string.Concat(lines.Select(static line => line + NewLine));
    }

    private static string WriteAttributeField(ParameterCheck check, string name)
    {
        string constructions = string.Join(Separator, check.AttributeConstructions);
        return $"private static readonly {ValidationAttributeArray} {FieldName(check, name)} = [{constructions}];";
    }

    private static string WriteValidation(ParameterCheck check, string name)
        => $"Validate(@{check.ParameterName}, \"{check.ParameterName}\", {FieldName(check, name)});";

    private static string FieldName(ParameterCheck check, string name) => $"s_{name}_{check.ParameterName}";
}
